DNS_OVERRIDES_STORE = Path("/etc/bind/dns_overrides.json")

def load_overrides_store() -> dict:
    """Loads stored host overrides and domain forwarders from JSON store."""
    if DNS_OVERRIDES_STORE.exists():
        try:
            with open(DNS_OVERRIDES_STORE) as f:
                return json.load(f)
        except Exception as e:
            logger.warning(f"Failed to read {DNS_OVERRIDES_STORE}: {e}")
    return {"host_overrides": [], "domain_forwarders": []}

def save_overrides_store(data: dict):
    """Saves host overrides and domain forwarders to persistent JSON store."""
    with open(DNS_OVERRIDES_STORE, "w") as f:
        json.dump(data, f, indent=2)
    try:
        os.chmod(DNS_OVERRIDES_STORE, 0o644)
    except Exception:
        pass

def sync_bind_overrides(data: dict):
    """Generates BIND9 RPZ zone and conditional domain forwarders, then reloads BIND9 and flushes cache."""
    BIND_RPZ_DB.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(str(BIND_RPZ_DB.parent), 0o755)
    except Exception:
        pass

    serial = int(time.time())

    # 1. db.rpz.overrides
    rpz_lines = [
        "$TTL 60",
        f"@ IN SOA localhost. root.localhost. ( {serial} 3h 1h 1w 1h )",
        "  IN NS localhost.",
        ""
    ]
    for h in data.get("host_overrides", []):
        fqdn = h["fqdn"].strip().rstrip(".")
        rtype = h.get("record_type", "A").upper()
        target = h["target"].strip()
        if rtype == "CNAME":
            if not target.endswith("."):
                target = f"{target}."
            rpz_lines.append(f"{fqdn} CNAME {target}")
        elif rtype == "TXT":
            clean_txt = target.replace('"', '\\"')
            rpz_lines.append(f'{fqdn} TXT "{clean_txt}"')
        else:
            rpz_lines.append(f"{fqdn} {rtype} {target}")

    with open(BIND_RPZ_DB, "w") as f:
        f.write("\n".join(rpz_lines) + "\n")
    try:
        os.chmod(str(BIND_RPZ_DB), 0o644)
    except Exception:
        pass

    # 2. named.conf.overrides
    conf_lines = [
        "// Autogenerated by ZclockID Management Appliance",
        'zone "rpz.overrides" {',
        "    type primary;",
        f'    file "{BIND_RPZ_DB}";',
        "    allow-query { any; };",
        "};",
        ""
    ]
    for d in data.get("domain_forwarders", []):
        dom = d["domain"].strip().rstrip(".").lower()
        policy = d.get("policy", "only")
        fwds = [ip.strip() for ip in d.get("forwarders", []) if ip.strip()]
        if fwds:
            fwd_str = "; ".join(fwds) + ";"
            conf_lines.append(f'zone "{dom}" {{')
            conf_lines.append(f"    type forward;")
            conf_lines.append(f"    forward {policy};")
            conf_lines.append(f"    forwarders {{ {fwd_str} }};")
            conf_lines.append("};\n")

    with open(BIND_OVERRIDES_CONF, "w") as f:
        f.write("\n".join(conf_lines) + "\n")
    try:
        os.chmod(str(BIND_OVERRIDES_CONF), 0o644)
    except Exception:
        pass

    code, _, stderr = run_cmd(["named-checkconf", "/etc/bind/named.conf"])
    if code != 0:
        raise HTTPException(status_code=400, detail=f"BIND9 syntax error in overrides: {stderr}")

    run_cmd(["rndc", "reload"])
    run_cmd(["rndc", "flush"])

    code, _, stderr = run_cmd(["named-checkconf", "/etc/bind/named.conf"])
    if code != 0:
        raise HTTPException(status_code=400, detail=f"BIND9 syntax error in overrides: {stderr}")

    run_cmd(["rndc", "reload"])
    run_cmd(["rndc", "flush"])

