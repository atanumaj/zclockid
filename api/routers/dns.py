def add_host_override(req: HostOverrideRequest):
    """Adds or updates a custom Host Override (FQDN to IP / CNAME mapping via BIND9 RPZ)."""
    clean_fqdn = req.fqdn.strip().rstrip(".").lower()
    if not clean_fqdn:
        raise HTTPException(status_code=400, detail="FQDN hostname is required.")

    store = load_overrides_store()
    hosts = [h for h in store.get("host_overrides", []) if not (h["fqdn"].lower() == clean_fqdn and h.get("record_type", "A").upper() == req.record_type.upper())]
    hosts.append({
        "id": str(uuid.uuid4())[:8],
        "fqdn": clean_fqdn,
        "record_type": req.record_type.upper(),
        "target": req.target.strip(),
        "description": req.description or ""
    })
    store["host_overrides"] = hosts
    sync_bind_overrides(store)
    save_overrides_store(store)
    log_audit("DNS_HOST_OVERRIDE_ADDED", "admin", clean_fqdn, "SUCCESS", {"type": req.record_type, "target": req.target})
    return {"status": "success", "message": f"Host override for '{clean_fqdn}' ({req.record_type} -> {req.target}) applied successfully."}

