@router.post("/doh/test")
def test_doh_resolution(req: DohTestRequest):
    """Executes a live DNS-over-HTTPS (DoH) query via RFC 8484 and decodes response."""
    target_qname = (req.qname or req.query_name or "inet.net").strip()
    target_rtype = (req.rtype or req.query_type or "A").strip().upper()

    try:
        q = dns.message.make_query(target_qname, target_rtype)
        wire_query = q.to_wire()
        b64_dns = base64.urlsafe_b64encode(wire_query).decode("utf-8").rstrip("=")

        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE

        start_time = time.time()
        doh_url = f"https://127.0.0.1/dns-query?dns={b64_dns}"
        req_obj = urllib.request.Request(doh_url, headers={"Accept": "application/dns-message"})

        with urllib.request.urlopen(req_obj, context=ctx, timeout=6) as resp:
            data = resp.read()
            duration_ms = round((time.time() - start_time) * 1000, 2)
            resp_msg = dns.message.from_wire(data)

            raw_answers = []
            formatted_answers = []
            for rrset in resp_msg.answer:
                for item in rrset:
                    rd_text = str(item)
                    type_str = dns.rdatatype.to_text(rrset.rdtype)
                    raw_answers.append({
                        "name": str(rrset.name),
                        "type": type_str,
                        "ttl": rrset.ttl,
                        "data": rd_text
                    })
                    formatted_answers.append(f"{str(rrset.name)} {rrset.ttl}s {type_str} {rd_text}")

            rcode_text = dns.rcode.to_text(resp_msg.rcode())
            return {
                "status": "ok",
                "success": True,
                "http_status": resp.status,
                "status_code": resp.status,
                "rcode": rcode_text,
                "latency_ms": duration_ms,
                "response_time_ms": duration_ms,
                "rtype": target_rtype,
                "answers": formatted_answers,
                "raw_answers": raw_answers,
                "answer_count": len(raw_answers),
                "query": f"{target_qname} IN {target_rtype}",
                "message": f"Successfully resolved {target_qname} via DoH in {duration_ms}ms ({len(raw_answers)} answers)."
            }
    except Exception as e:
        return {
            "status": "error",
            "success": False,
            "detail": str(e),
            "error": f"DoH query failed: {str(e)}",
            "query": f"{target_qname} IN {target_rtype}"
        }

@router.post("/records")
def add_dns_record(req: DnsRecordRequest):
    """Adds a standard (A, AAAA, CNAME, MX, TXT, NS, PTR, SRV, SOA, CAA) DNS record with TTL."""
    admin_user, admin_pass = get_ad_creds()
    rtype = req.record_type.upper()
    target_ttl = int(req.ttl) if req.ttl and req.ttl > 0 else 900

    if rtype == "CAA":
        raise HTTPException(
            status_code=400,
            detail="Active Directory BIND9/Samba DLZ: Direct creation of CAA records is not supported by the Samba AD DNS engine. Please configure CAA records at your edge proxy (e.g. Cloudflare) or authoritative upstream DNS."
        )
    elif rtype == "SOA":
        raise HTTPException(
            status_code=400,
            detail="Active Directory BIND9/Samba DLZ: Zone SOA record is automatically generated at the zone apex (@). To modify SOA timers or primary nameserver, use the record Edit action."
        )

    # Prepare formatted data string
    if rtype == "SRV":
        port = req.port or 88
        priority = req.priority or 0
        weight = req.weight or 100
        target = req.record_data.strip()
        data_str = f"{target} {port} {priority} {weight}"
    elif rtype == "MX":
        target = req.record_data.strip()
        priority = req.priority if req.priority is not None else 10
        if " " in target:
            data_str = target
        else:
            data_str = f"{target} {priority}"
    elif rtype == "TXT":
        data_str = req.record_data.strip()
    else:
        data_str = req.record_data.strip()

    # Try fast in-process RPC to set custom TTL directly
    added_via_rpc = False
    try:
        from samba.netcmd.dns import DnsConnWrapper, dns_type_flag, data_to_dns_record
        from samba.param import LoadParm
        from samba.credentials import Credentials
        from samba.dcerpc import dnsserver

        lp = LoadParm()
        lp.load(str(SMB_CONF_FILE))
        creds = Credentials()
        creds.guess(lp)
        creds.set_username(admin_user)
        creds.set_password(admin_pass)
        conn = DnsConnWrapper("127.0.0.1", lp, creds)

        record_type = dns_type_flag(rtype)
        rec = data_to_dns_record(record_type, data_str)
        rec.dwTtlSeconds = target_ttl
        add_rec_buf = dnsserver.DNS_RPC_RECORD_BUF()
        add_rec_buf.rec = rec
        conn.DnssrvUpdateRecord2(dnsserver.DNS_CLIENT_VERSION_LONGHORN, 0, "127.0.0.1", req.zone, req.record_name, add_rec_buf, None)
        added_via_rpc = True
    except Exception as e:
        logger.warning(f"In-process RPC DNS add failed ({e}), falling back to CLI")

    if not added_via_rpc:
        cmd = ["samba-tool", "dns", "add", "127.0.0.1", req.zone, req.record_name, rtype, data_str, f"-U{admin_user}", f"--password={admin_pass}"]
        code, stdout, stderr = run_cmd(cmd, timeout=15)
        if code != 0:
            raise HTTPException(status_code=400, detail=f"Failed to add DNS record: {stderr or stdout}")

    _DNS_RECORDS_CACHE.pop(req.zone, None)
    log_audit("DNS_RECORD_ADDED", "admin", f"{req.record_name}.{req.zone}", "SUCCESS", {"type": req.record_type, "data": req.record_data, "ttl": target_ttl})
    return {"status": "success", "message": f"{req.record_type} record '{req.record_name}' added to zone {req.zone} (TTL: {target_ttl}s)."}

@router.put("/records")
def update_dns_record(req: DnsRecordUpdateRequest):
    """Updates an existing DNS record data / target and TTL in Active Directory DNS."""
    admin_user, admin_pass = get_ad_creds()
    old_clean = req.old_data.strip()
    new_clean = req.new_data.strip()
    rtype = req.record_type.upper()
    target_ttl = int(req.ttl) if req.ttl and req.ttl > 0 else 900

    if rtype == "SRV":
        port = req.port or 88
        priority = req.priority or 0
        weight = req.weight or 100
        target = new_clean
        if "(" in target:
            target = target.split("(")[0].strip()
        new_data_str = f"{target} {port} {priority} {weight}"

        if "(" in old_clean:
            parts = old_clean.split("(")
            t = parts[0].strip()
            sub = parts[1].replace(")", "").split(",")
            if len(sub) == 3:
                old_clean = f"{t} {sub[0].strip()} {sub[1].strip()} {sub[2].strip()}"
    elif rtype == "MX":
        target = new_clean
        if "(" in target:
            parts = target.split("(")
            target = f"{parts[0].strip()} {parts[1].replace(')', '').strip()}"
        elif " " not in target:
            priority = req.priority if req.priority is not None else 10
            target = f"{target} {priority}"
        new_data_str = target

        if "(" in old_clean:
            parts = old_clean.split("(")
            t = parts[0].strip()
            p = parts[1].replace(")", "").strip()
            old_clean = f"{t} {p}"
    else:
        new_data_str = new_clean

    updated_via_rpc = False
    try:
        from samba.netcmd.dns import DnsConnWrapper, dns_type_flag, data_to_dns_record
        from samba.param import LoadParm
        from samba.credentials import Credentials
        from samba.dcerpc import dnsserver

        lp = LoadParm()
        lp.load(str(SMB_CONF_FILE))
        creds = Credentials()
        creds.guess(lp)
        creds.set_username(admin_user)
        creds.set_password(admin_pass)
        conn = DnsConnWrapper("127.0.0.1", lp, creds)

        record_type = dns_type_flag(rtype)
        old_rec = data_to_dns_record(record_type, old_clean)
        new_rec = data_to_dns_record(record_type, new_data_str)
        new_rec.dwTtlSeconds = target_ttl

        buf_new = dnsserver.DNS_RPC_RECORD_BUF()
        buf_new.rec = new_rec
        buf_del = dnsserver.DNS_RPC_RECORD_BUF()
        buf_del.rec = old_rec

        conn.DnssrvUpdateRecord2(dnsserver.DNS_CLIENT_VERSION_LONGHORN, 0, "127.0.0.1", req.zone, req.record_name, buf_new, buf_del)
        updated_via_rpc = True
    except Exception as e:
        logger.warning(f"In-process RPC DNS update failed ({e}), falling back to CLI")

    if not updated_via_rpc:
        cmd = ["samba-tool", "dns", "update", "127.0.0.1", req.zone, req.record_name, rtype, old_clean, new_data_str, f"-U{admin_user}", f"--password={admin_pass}"]
        code, stdout, stderr = run_cmd(cmd, timeout=15)
        if code != 0:
            raise HTTPException(status_code=400, detail=f"Failed to update DNS record: {stderr or stdout}")

    _DNS_RECORDS_CACHE.pop(req.zone, None)
    log_audit("DNS_RECORD_UPDATED", "admin", f"{req.record_name}.{req.zone}", "SUCCESS", {
        "type": req.record_type, "old_data": req.old_data, "new_data": req.new_data, "ttl": target_ttl
    })
    return {"status": "success", "message": f"{req.record_type} record '{req.record_name}' updated successfully in zone {req.zone} (TTL: {target_ttl}s)."}

@router.delete("/records")
def delete_dns_record(zone: str, record_name: str, record_type: str, record_data: str):
    """Deletes a custom DNS record from Active Directory DNS. Default service & Kerberos records cannot be deleted."""
    if is_protected_dns_record(record_name, record_type, zone):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=f"Protected System Record: Active Directory & Kerberos service records ('{record_name}') cannot be deleted. Only custom records may be deleted."
        )

    admin_user, admin_pass = get_ad_creds()
    clean_data = record_data.strip()
    rtype = record_type.upper()
    if rtype == "SRV" and "(" in clean_data:
        parts = clean_data.split("(")
        t = parts[0].strip()
        sub = parts[1].replace(")", "").split(",")
        if len(sub) == 3:
            clean_data = f"{t} {sub[0].strip()} {sub[1].strip()} {sub[2].strip()}"
    elif rtype == "MX" and "(" in clean_data:
        parts = clean_data.split("(")
        t = parts[0].strip()
        p = parts[1].replace(")", "").strip()
        clean_data = f"{t} {p}"
    elif rtype == "TXT" and "," in clean_data and not clean_data.startswith('"'):
        clean_data = clean_data.replace(",", " ")

    cmd = ["samba-tool", "dns", "delete", "127.0.0.1", zone, record_name, rtype, clean_data, f"-U{admin_user}", f"--password={admin_pass}"]
    code, stdout, stderr = run_cmd(cmd, timeout=15)
    if code != 0:
        raise HTTPException(status_code=400, detail=f"Failed to delete DNS record: {stderr or stdout}")

    _DNS_RECORDS_CACHE.pop(zone, None)
    log_audit("DNS_RECORD_DELETED", "admin", f"{record_name}.{zone}", "SUCCESS", {"type": record_type})
    return {"status": "success", "message": f"Custom record '{record_name}' deleted from zone {zone}."}

@router.get("/diagnostics")
def get_dns_diagnostics():
    """Runs verification tests for Kerberos, LDAP, and Kpasswd service discovery records."""
    realm = "inet.net"
    if SMB_CONF_FILE.exists():
        with open(SMB_CONF_FILE) as f:
            for line in f:
                if "realm =" in line:
                    realm = line.split("=")[1].strip().lower()

    checks = []
    code_k, out_k, _ = run_cmd(["dig", "+short", f"_kerberos._tcp.{realm}", "SRV", "@127.0.0.1"], timeout=5)
    checks.append({
        "service": "Kerberos KDC (TCP Port 88)",
        "record": f"_kerberos._tcp.{realm}",
        "status": "PASS" if code_k == 0 and out_k.strip() else "FAIL",
        "result": out_k.strip() or "No SRV record returned"
    })
    code_l, out_l, _ = run_cmd(["dig", "+short", f"_ldap._tcp.{realm}", "SRV", "@127.0.0.1"], timeout=5)
    checks.append({
        "service": "LDAP Directory (TCP Port 389)",
        "record": f"_ldap._tcp.{realm}",
        "status": "PASS" if code_l == 0 and out_l.strip() else "FAIL",
        "result": out_l.strip() or "No SRV record returned"
    })
    code_p, out_p, _ = run_cmd(["dig", "+short", f"_kpasswd._tcp.{realm}", "SRV", "@127.0.0.1"], timeout=5)
    checks.append({
        "service": "Kerberos Password Change (TCP Port 464)",
        "record": f"_kpasswd._tcp.{realm}",
        "status": "PASS" if code_p == 0 and out_p.strip() else "FAIL",
        "result": out_p.strip() or "No SRV record returned"
    })
    code_f, out_f, _ = run_cmd(["dig", "+short", "cloudflare.com", "A", "@127.0.0.1"], timeout=5)
    checks.append({
        "service": "Upstream DNS Forwarding Recursion",
        "record": "cloudflare.com (A)",
        "status": "PASS" if code_f == 0 and out_f.strip() else "FAIL",
        "result": out_f.strip().splitlines()[0] if out_f.strip() else "Upstream resolution failed"
    })

    all_passed = all(c["status"] == "PASS" for c in checks)
    return {
        "status": "HEALTHY" if all_passed else "DEGRADED",
        "realm": realm,
        "diagnostics": checks
    }

